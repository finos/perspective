use web_sys::MouseEvent;
use yew::Callback;

/// Gate a `mousedown` callback to the primary button, so a right-click (which
/// opens the viewer context menu) never also triggers the control under it.
pub fn left_click(callback: Callback<MouseEvent>) -> Callback<MouseEvent> {
    Callback::from(move |event: MouseEvent| {
        if event.button() == 0 {
            callback.emit(event);
        }
    })
}
